import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const entries = [];
for (const name of ['protocol.mjs', 'json.mjs', 'input-contract.mjs']) {
  entries.push([name, createHash('sha256').update(await readFile(join(root, name))).digest('hex')]);
}
await writeFile(join(root, 'portable-runtime-hashes.mjs'), '// Generated by local/build-portable-runtime-hashes.mjs; no filesystem API is used in Forge.\n'
  + 'export const PORTABLE_RUNTIME_HASHES = Object.freeze(' + JSON.stringify(Object.fromEntries(entries), null, 2) + ');\n');
